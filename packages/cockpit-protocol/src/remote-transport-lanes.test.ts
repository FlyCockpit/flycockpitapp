    const fragments = fragmentFrame("interactive", frameId, corrupted);
    expect(fragments.length).toBeGreaterThan(1);
    const reassembler = new RemoteFragmentReassembler("client");
    // Each fragment decodes cleanly on its own.
    for (const fragment of fragments.slice(0, -1)) {
      const wire = decodeRemoteCarrierFragment(encodeRemoteCarrierFragment(fragment));
      expect(await reassembler.accept(wire, 0)).toBeUndefined();
    }
