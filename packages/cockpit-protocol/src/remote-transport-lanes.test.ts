describe("daemon-wire bulk schemas reject what Rust rejects", () => {
  it("validates opaque ids with the landed codec, not a regex", () => {
    const valid = {
      transfer_id: "AQIDBAUGBwgJCgsMDQ4PEA",
      total_length: "12",
      sha256: "ab".repeat(32),
      mime_class: "archive",
    };
    expect(bulkTransferRefSchema.safeParse(valid).success).toBe(true);

    // The all-zero id matches /^[A-Za-z0-9_-]{22}$/ but Rust's
    // tag_protocol_id_bytes rejects it, so the schema must too.
    expect(
      bulkTransferRefSchema.safeParse({ ...valid, transfer_id: "AAAAAAAAAAAAAAAAAAAAAA" }).success,
    ).toBe(false);
    for (const bad of [
      "AQIDBAUGBwgJCgsMDQ4PE",
      "AQIDBAUGBwgJCgsMDQ4PEA=",
      "AQIDBAUGBwgJCgsMDQ4P+A",
    ]) {
      expect(bulkTransferRefSchema.safeParse({ ...valid, transfer_id: bad }).success).toBe(false);
    }
  });

  it("bounds chunk indexes at u32, as Rust's type does", () => {
    const base = {
      v: PROTOCOL_VERSION,
      kind: "req",
      id: "11111111-1111-4111-8111-111111111111",
      request: "read_bulk_transfer_chunk",
      params: { transfer_id: "AQIDBAUGBwgJCgsMDQ4PEA", chunk_index: 7 },
    };
    expect(clientEnvelopeSchema.safeParse(base).success).toBe(true);
    expect(
      clientEnvelopeSchema.safeParse({
        ...base,
        params: { ...base.params, chunk_index: 0xffffffff },
      }).success,
    ).toBe(true);
    // One past u32: Rust cannot deserialize it, so neither may the schema.
    expect(
      clientEnvelopeSchema.safeParse({
        ...base,
        params: { ...base.params, chunk_index: 4294967296 },
      }).success,
    ).toBe(false);
    expect(
      clientEnvelopeSchema.safeParse({
        ...base,
        params: { ...base.params, chunk_index: -1 },
      }).success,
    ).toBe(false);
  });
});
