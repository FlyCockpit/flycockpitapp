/**
 * Fixture rows, typed explicitly.
 *
 * The JSON files are generated by Rust, so their inferred types carry optional
 * members (large vectors omit `encodedHex`). Normalising through these
 * interfaces keeps the assertions readable and the access checked.
 */
interface PayloadSpec {
  readonly fill: number;
  readonly length: number;
}

