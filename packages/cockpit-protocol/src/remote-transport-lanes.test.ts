    const reassembler = new RemoteFragmentReassembler("client");
    const first = await makeFragments(1);
    expect(await reassembler.accept(first[0]!, 0)).toBeUndefined();
    expect(await reassembler.accept(first[0]!, 0)).toBeUndefined();
