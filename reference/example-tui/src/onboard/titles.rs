pub fn width(lines: &[&str]) -> u16 {
    lines
        .iter()
        .map(|line| line.chars().count() as u16)
        .max()
        .unwrap_or(0)
}

pub fn height(lines: &[&str]) -> u16 {
    lines.len() as u16
}

